"""CSS Custom Properties & Tailwind v4 @theme Exporter for dnk_brand_typostyle."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml


def _extract_value(token_node: Any) -> str:
    """Extract string value from DTCG token object or primitive."""
    if isinstance(token_node, dict):
        if "$value" in token_node:
            return str(token_node["$value"])
        if "value" in token_node:
            return str(token_node["value"])
    return str(token_node)


def generate_css_from_spec(spec: dict[str, Any], include_tailwind_v4: bool = True) -> str:
    """Compile design token specification dictionary into CSS Custom Properties."""
    brand_name = spec.get("meta", {}).get("brand_name", "DNK Brand Theme")
    schema_version = spec.get("schema_version", "dtcg-2025.10")

    root_lines: list[str] = []
    theme_lines: list[str] = []

    # 1. Primitive Colors
    primitives_color = spec.get("primitives", {}).get("color", {})
    for group_name, group_tokens in primitives_color.items():
        if not isinstance(group_tokens, dict):
            continue
        for shade, token_obj in group_tokens.items():
            val = _extract_value(token_obj)
            var_name = f"--color-primitive-{group_name}-{shade}"
            root_lines.append(f"  {var_name}: {val};")

    # 2. Semantic Colors (60-30-10 CRO)
    semantic_color = spec.get("semantic", {}).get("color", {})
    for token_name, token_obj in semantic_color.items():
        val = _extract_value(token_obj)
        var_name = f"--color-{token_name}"
        root_lines.append(f"  {var_name}: {val};")
        theme_lines.append(f"  {var_name}: var({var_name});")

    # 3. Typography Families
    families = spec.get("typography", {}).get("families", {})
    for fam_name, fam_obj in families.items():
        val = _extract_value(fam_obj)
        var_name = f"--font-{fam_name}"
        root_lines.append(f"  {var_name}: {val};")
        theme_lines.append(f"  {var_name}: var({var_name});")

    # 4. Typography Modular Scale
    scale = spec.get("typography", {}).get("scale", {})
    for step_name, step_obj in scale.items():
        if not isinstance(step_obj, dict):
            continue
        rem_val = step_obj.get("rem", 1.0)
        lh_val = step_obj.get("line_height", 1.5)
        weight_val = step_obj.get("weight", 400)
        tracking_val = step_obj.get("letter_spacing", "0em")

        root_lines.append(f"  --text-{step_name}: {rem_val}rem;")
        root_lines.append(f"  --text-{step_name}--line-height: {lh_val};")
        root_lines.append(f"  --text-{step_name}--font-weight: {weight_val};")
        root_lines.append(f"  --text-{step_name}--letter-spacing: {tracking_val};")

        theme_lines.append(f"  --text-{step_name}: {rem_val}rem;")
        theme_lines.append(f"  --text-{step_name}--line-height: {lh_val};")

    # 5. 8pt Spacing Grid
    spacing = spec.get("spacing", {})
    for space_name, space_obj in spacing.items():
        val = _extract_value(space_obj)
        var_name = f"--spacing-{space_name}"
        root_lines.append(f"  {var_name}: {val};")
        theme_lines.append(f"  {var_name}: {val};")

    # 6. Border Radii
    radii = spec.get("radii", {})
    for radius_name, radius_obj in radii.items():
        val = _extract_value(radius_obj)
        var_name = f"--radius-{radius_name}"
        root_lines.append(f"  {var_name}: {val};")
        theme_lines.append(f"  {var_name}: {val};")

    blocks = [
        f"/* Generated by dnk_brand_typostyle | Brand: {brand_name} | Schema: {schema_version} */",
        ":root {",
        *root_lines,
        "}",
    ]

    if include_tailwind_v4:
        blocks.extend(
            [
                "",
                "@theme {",
                *theme_lines,
                "}",
            ]
        )

    return "\n".join(blocks) + "\n"


def load_spec(spec_path: Path) -> dict[str, Any]:
    """Load YAML or JSON token specification."""
    raw = spec_path.read_text(encoding="utf-8")
    if spec_path.suffix.lower() == ".json":
        return json.loads(raw)
    return yaml.safe_load(raw)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Export W3C DTCG / Google DESIGN.md tokens to CSS Custom Properties."
    )
    parser.add_argument(
        "--spec",
        required=True,
        type=Path,
        help="Path to YAML or JSON design token specification.",
    )
    parser.add_argument(
        "--output",
        required=False,
        type=Path,
        help="Optional output CSS file path. Prints to stdout if omitted.",
    )
    args = parser.parse_args(argv)

    if not args.spec.exists():
        sys.stderr.write(f"Error: Spec file not found: {args.spec}\n")
        return 1

    spec_data = load_spec(args.spec)
    css_output = generate_css_from_spec(spec_data)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(css_output, encoding="utf-8")
        print(json.dumps({"status": "PASS", "output_path": str(args.output), "bytes": len(css_output)}))
    else:
        sys.stdout.write(css_output)

    return 0


if __name__ == "__main__":
    sys.exit(main())
